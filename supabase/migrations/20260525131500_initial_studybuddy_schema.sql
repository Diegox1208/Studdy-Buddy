CREATE OR REPLACE VIEW vista_resumen_estudiante AS
SELECT
    e.id,
    e.nombre || ' ' || e.apellido AS nombre_completo,
    e.edad,
    e.nivel_educativo,
    COUNT(DISTINCT c.id) AS total_clases,
    SUM(c.duracion_horas) AS horas_totales,
    AVG(n.porcentaje) AS promedio_notas,
    metrics.autonomia_porcentaje,
    metrics.fluidez_porcentaje,
    metrics.resiliencia_porcentaje,
    metrics.racha_dias_consecutivos
FROM estudiantes e
LEFT JOIN clases c ON e.id = c.estudiante_id AND c.estado = 'completada'
LEFT JOIN notas n ON e.id = n.estudiante_id
LEFT JOIN LATERAL (
    SELECT autonomia_porcentaje, fluidez_porcentaje, resiliencia_porcentaje, racha_dias_consecutivos
    FROM metricas_objetivas mo
    WHERE mo.estudiante_id = e.id
    ORDER BY mo.fecha DESC, mo.id DESC
    LIMIT 1
) metrics ON TRUE
GROUP BY e.id, metrics.autonomia_porcentaje, metrics.fluidez_porcentaje, metrics.resiliencia_porcentaje, metrics.racha_dias_consecutivos;

CREATE OR REPLACE VIEW vista_calendario_completo AS
SELECT
    c.id,
    c.fecha,
    c.hora_inicio,
    c.hora_fin,
    c.duracion_horas,
    c.modalidad,
    c.direccion,
    e.nombre || ' ' || e.apellido AS estudiante,
    p.nombre || ' ' || p.apellido AS profesor,
    m.nombre AS materia,
    m.nivel,
    c.estado,
    a.estado AS asistencia
FROM clases c
JOIN estudiantes e ON c.estudiante_id = e.id
JOIN profesores p ON c.profesor_id = p.id
JOIN materias m ON c.materia_id = m.id
LEFT JOIN asistencia a ON c.id = a.clase_id AND e.id = a.estudiante_id;

