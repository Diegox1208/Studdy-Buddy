-- Study Buddy Supabase/Postgres schema

CREATE TABLE IF NOT EXISTS estudiantes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    edad INTEGER,
    fecha_nacimiento DATE,
    nivel_educativo VARCHAR(50),
    foto_perfil VARCHAR(255),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso TIMESTAMP,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS profesores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    especialidad VARCHAR(100),
    foto_perfil VARCHAR(255),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso TIMESTAMP,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS materias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    nivel VARCHAR(50),
    creditos INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS syllabus (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id INTEGER NOT NULL REFERENCES materias(id),
    profesor_id INTEGER NOT NULL REFERENCES profesores(id),
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT,
    objetivos TEXT,
    contenido TEXT,
    metodologia TEXT,
    evaluacion TEXT,
    bibliografia TEXT,
    "año_academico" VARCHAR(20),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id INTEGER NOT NULL REFERENCES materias(id),
    profesor_id INTEGER NOT NULL REFERENCES profesores(id),
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_horas NUMERIC(4,2),
    modalidad VARCHAR(20) NOT NULL,
    direccion VARCHAR(255),
    link_virtual VARCHAR(255),
    estado VARCHAR(20) DEFAULT 'programada',
    notas_clase TEXT,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS asistencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id INTEGER NOT NULL REFERENCES clases(id),
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    materia_id INTEGER NOT NULL REFERENCES materias(id),
    tipo_evaluacion VARCHAR(50) NOT NULL,
    titulo VARCHAR(200),
    calificacion NUMERIC(5,2) NOT NULL,
    calificacion_maxima NUMERIC(5,2) DEFAULT 100,
    porcentaje NUMERIC(5,2),
    fecha_evaluacion DATE NOT NULL,
    trimestre VARCHAR(20),
    comentarios TEXT,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS horas_estudiante (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    materia_id INTEGER NOT NULL REFERENCES materias(id),
    total_horas NUMERIC(6,2) DEFAULT 0,
    mes VARCHAR(7),
    "año" INTEGER,
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reportes_clase (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id INTEGER NOT NULL REFERENCES clases(id),
    profesor_id INTEGER NOT NULL REFERENCES profesores(id),
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    tema_cubierto TEXT NOT NULL,
    objetivos_cumplidos TEXT,
    "desempeño_estudiante" TEXT,
    areas_mejora TEXT,
    tareas_asignadas TEXT,
    observaciones TEXT,
    fecha_reporte TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS metacognicion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    clase_id INTEGER REFERENCES clases(id),
    fecha DATE NOT NULL,
    comprension_tema INTEGER CHECK(comprension_tema BETWEEN 1 AND 5),
    dificultad_percibida INTEGER CHECK(dificultad_percibida BETWEEN 1 AND 5),
    confianza_nivel INTEGER CHECK(confianza_nivel BETWEEN 1 AND 5),
    que_aprendi TEXT,
    que_fue_dificil TEXT,
    que_estrategias_use TEXT,
    como_mejorar TEXT,
    estado_animo VARCHAR(50),
    nivel_estres INTEGER CHECK(nivel_estres BETWEEN 1 AND 5),
    tiempo_estudio_horas NUMERIC(4,2),
    esfuerzo_percibido INTEGER CHECK(esfuerzo_percibido BETWEEN 1 AND 5),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS metricas_objetivas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    fecha DATE NOT NULL,
    autonomia_porcentaje NUMERIC(5,2),
    solicitudes_ayuda INTEGER DEFAULT 0,
    tiempo_sin_ayuda_minutos INTEGER DEFAULT 0,
    fluidez_porcentaje NUMERIC(5,2),
    velocidad_respuesta_segundos NUMERIC(6,2),
    precision_porcentaje NUMERIC(5,2),
    resiliencia_porcentaje NUMERIC(5,2),
    intentos_antes_exito INTEGER DEFAULT 0,
    persistencia_score NUMERIC(5,2),
    racha_dias_consecutivos INTEGER DEFAULT 0,
    ultima_actividad DATE,
    nivel_dominio VARCHAR(50),
    progreso_semanal NUMERIC(5,2),
    promedio_general NUMERIC(5,2),
    tiempo_sesion_minutos INTEGER,
    sesiones_completadas INTEGER DEFAULT 0,
    ejercicios_completados INTEGER DEFAULT 0,
    fecha_calculo TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS estilo_cognitivo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    tipo_estilo VARCHAR(50) NOT NULL,
    nivel_intensidad INTEGER CHECK(nivel_intensidad BETWEEN 1 AND 5),
    observaciones TEXT,
    fecha_evaluacion DATE NOT NULL,
    evaluado_por INTEGER REFERENCES profesores(id),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS objetivos_aprendizaje (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
    materia_id INTEGER NOT NULL REFERENCES materias(id),
    objetivo TEXT NOT NULL,
    descripcion TEXT,
    fecha_inicio DATE NOT NULL,
    fecha_objetivo DATE,
    estado VARCHAR(20) DEFAULT 'en_progreso',
    progreso_porcentaje NUMERIC(5,2) DEFAULT 0,
    fecha_completado DATE,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mensajes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remitente_tipo VARCHAR(20) NOT NULL,
    remitente_id INTEGER NOT NULL,
    destinatario_tipo VARCHAR(20) NOT NULL,
    destinatario_id INTEGER NOT NULL,
    asunto VARCHAR(200),
    mensaje TEXT NOT NULL,
    leido BOOLEAN DEFAULT FALSE,
    fecha_lectura TIMESTAMP,
    fecha_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_folders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(estudiante_id, name)
);

CREATE TABLE IF NOT EXISTS pizarra_paginas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    folder_id INTEGER REFERENCES student_folders(id) ON DELETE SET NULL,
    titulo TEXT NOT NULL,
    pagina_data TEXT NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    folder_id INTEGER REFERENCES student_folders(id) ON DELETE SET NULL,
    filename TEXT NOT NULL,
    filepath TEXT NOT NULL,
    category TEXT DEFAULT 'casillero',
    upload_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

